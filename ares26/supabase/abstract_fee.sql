-- ARES'26: PKR 500 printing & setup fee for accepted abstracts, paid through a private per-abstract page
-- (#abstract-submission-<ref_no>). Run once in Supabase > SQL Editor. Safe to re-run.
-- Run supabase/abstracts_approved.sql first (it defines the approved-only submit rule and is_approved()).

-- 1. Public reference number used in the link, plus the fee payment fields
alter table public.abstracts add column if not exists ref_no bigint generated always as identity (start with 1001);
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'abstracts_ref_no_key') then
    alter table public.abstracts add constraint abstracts_ref_no_key unique (ref_no);
  end if;
end $$;

alter table public.abstracts add column if not exists fee_status text not null default 'Unpaid';
alter table public.abstracts drop constraint if exists fee_status_values;
alter table public.abstracts add constraint fee_status_values check (fee_status in ('Unpaid','Pending','Approved','Rejected'));
alter table public.abstracts add column if not exists fee_amount numeric;
alter table public.abstracts add column if not exists fee_tx_id text;
alter table public.abstracts add column if not exists fee_account_name text;
alter table public.abstracts add column if not exists fee_tx_date timestamptz;
alter table public.abstracts add column if not exists fee_proof_path text;

alter table public.abstracts drop constraint if exists fee_proof_own_folder;
alter table public.abstracts add constraint fee_proof_own_folder
  check (fee_proof_path is null or fee_proof_path like user_id::text || '/%');
alter table public.abstracts drop constraint if exists fee_field_limits;
alter table public.abstracts add constraint fee_field_limits check (
  char_length(coalesce(fee_tx_id,'')) <= 100 and char_length(coalesce(fee_account_name,'')) <= 200 and
  (fee_amount is null or (fee_amount > 0 and fee_amount < 10000000)));

-- 2. New abstracts always start unpaid (and still need an Approved registration)
drop policy if exists "abstracts insert approved own" on public.abstracts;
create policy "abstracts insert approved own" on public.abstracts for insert to authenticated
  with check (user_id = auth.uid() and status = 'Submitted' and fee_status = 'Unpaid' and fee_proof_path is null and public.is_approved());

-- 3. The author may upload fee details ONLY while the abstract is Accepted and the fee is Unpaid / Rejected
drop policy if exists "abstracts pay own" on public.abstracts;
create policy "abstracts pay own" on public.abstracts for update to authenticated
  using (user_id = auth.uid() and status = 'Accepted' and fee_status in ('Unpaid','Rejected'))
  with check (user_id = auth.uid());

-- 4. Non-admins can change nothing except the fee payment fields; uploading a proof moves the fee to Pending
create or replace function public.protect_abstract() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    new.id := old.id; new.user_id := old.user_id; new.title := old.title; new.discipline := old.discipline;
    new.category := old.category; new.body := old.body; new.file_path := old.file_path;
    new.status := old.status; new.created_at := old.created_at; new.ref_no := old.ref_no;
    if new.fee_proof_path is distinct from old.fee_proof_path then new.fee_status := 'Pending';
    else new.fee_status := old.fee_status; end if;
  end if;
  return new;
end $$;
drop trigger if exists protect_abstract_trg on public.abstracts;
create trigger protect_abstract_trg before update on public.abstracts for each row execute function public.protect_abstract();

-- 5. Payment link must be GENERATED by an admin (Admin > Abstract fees) before the author can pay
alter table public.abstracts add column if not exists fee_link_at timestamptz;

drop policy if exists "abstracts pay own" on public.abstracts;
create policy "abstracts pay own" on public.abstracts for update to authenticated
  using (user_id = auth.uid() and status = 'Accepted' and fee_link_at is not null and fee_status in ('Unpaid','Rejected'))
  with check (user_id = auth.uid());

create or replace function public.protect_abstract() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    new.id := old.id; new.user_id := old.user_id; new.title := old.title; new.discipline := old.discipline;
    new.category := old.category; new.body := old.body; new.file_path := old.file_path;
    new.status := old.status; new.created_at := old.created_at; new.ref_no := old.ref_no;
    new.fee_link_at := old.fee_link_at;
    if new.fee_proof_path is distinct from old.fee_proof_path then new.fee_status := 'Pending';
    else new.fee_status := old.fee_status; end if;
  end if;
  return new;
end $$;
